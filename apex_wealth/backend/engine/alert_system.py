"""
Section 6 — Tri-Horizon Risk & Alert Engine (`engine/alert_system.py`).

Implements continuous monitoring across 3 temporal horizons (Past, Present, Future)
and computes the Unified Portfolio Health Gauge Score (0–100):

1. Past Horizon (Compliance & Audit Verification):
   - `WARN_PAST_SETTLE_VIOLATION`: Triggered if executed order committed cash bound by unsettled T+2 locks.
   - `WARN_PAST_TAX_MISMATCH`: Triggered if Short-Term CGT lot (tau = 0.075) was liquidated when an eligible
     Long-Term CGT lot (tau = 0.050) was available.
   - `WARN_PAST_MERKLE_MISMATCH`: Triggered if local execution HMAC hash fails to verify against anchored R_Merkle.

2. Present Horizon (Microstructure & Execution Protection):
   - `WARN_PRES_VPIN_TOXICITY`: Triggered when VPIN > mu_VPIN + 2*sigma_VPIN (> 0.50). Pauses slicing engine
     and reduces Health Gauge score.
   - `WARN_PRES_LOB_DEPLETION`: Triggered when child slice size q_child > 0.15 * Depth_LOB. Throttles execution pace.
   - `WARN_PRES_HAWKES_SWEEP`: Triggered when self-exciting broker sweep intensity lambda(t) >= 0.85,
     detecting predatory broker syndicate loops.
   - `WARN_PRES_SLIPPAGE_EXCEEDED`: Triggered when filled price deviates > 25 bps from decision price.

3. Future Horizon (Predictive Drift & Structural Risks):
   - `WARN_FUT_VAR_EXPANSION`: Triggered when projected 1-day VaR_99 > 3.5% of portfolio NAV.
   - `WARN_FUT_RANK_DECAY`: Triggered when a held asset's Schur rank degrades to position 14 or 15
     (near the rank-15 exit threshold).
   - `WARN_FUT_PROMOTER_CLIFF`: Alerts compliance 14 days prior to promoter share lock-in expiration.
   - `WARN_FUT_COND_NUMBER`: Triggered when covariance matrix condition number kappa > 100,
     initiating Ledoit-Wolf shrinkage.

4. Unified Portfolio Health Gauge (0–100 Score):
   S_health = max(0, min(100, 100 * (1 - [0.35*(VaR_99/VaR_max) + 0.30*VPIN + 0.20*(C_locked/C_total) + 0.15*(S_locked/S_total)])))
   with an instant 40-point microstructure penalty if VPIN >= 0.70 or Hawkes intensity lambda(t) >= 0.85.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, List, Optional, Sequence


class HorizonType(str, Enum):
    PAST = "PAST"
    PRESENT = "PRESENT"
    FUTURE = "FUTURE"


class AlertSeverity(str, Enum):
    INFO = "INFO"
    WARNING = "WARNING"
    CRITICAL = "CRITICAL"


@dataclass
class TriHorizonAlert:
    """Structured alert generated by the Tri-Horizon Risk & Alert Engine."""

    alert_id: str
    code: str
    horizon: str
    severity: str
    symbol: Optional[str]
    title: str
    message: str
    metric_value: float
    threshold_value: float
    remediation_action: str
    timestamp: str


@dataclass
class HealthGaugeTelemetry:
    """Complete telemetry payload for Component 1: Unified Portfolio Health Gauge (0–100)."""

    score: int
    raw_score: float
    status: str  # "Optimal" | "Attention" | "Critical"
    status_color: str  # "#10B981" | "#F59E0B" | "#EF4444"
    var_99_pct: float
    var_max_pct: float
    cvar_1d_pct: float
    vpin: float
    hawkes_intensity: float
    c_locked_ratio: float
    s_locked_ratio: float
    cdsc_t2_lockup_pct: float
    microstructure_penalty_applied: bool
    penalty_points: int
    slicing_engine_paused: bool


class TriHorizonAlertEngine:
    """
    Tri-Horizon Risk & Alert Engine covering Past, Present, and Future institutional safeguards.
    """

    VAR_MAX_DEFAULT: float = 0.035  # 3.5% NAV ceiling for 1-day VaR_99

    def compute_portfolio_health_score(
        self,
        var_99: float,
        vpin: float,
        c_locked_ratio: float,
        s_locked_ratio: float,
        hawkes_intensity: float = 0.04,
        var_max: float = 0.035,
        cvar_1d: Optional[float] = None,
    ) -> HealthGaugeTelemetry:
        """
        Compute the Unified Portfolio Health Gauge Score (0–100):
            S_health = max(0, min(100, 100 * (1 - [
                0.35 * (VaR_99 / VaR_max)
              + 0.30 * VPIN
              + 0.20 * (C_locked / C_total)
              + 0.15 * (S_locked / S_total)
            ])))

        Microstructure Triggers:
            If VPIN >= 0.70 (Order Flow Toxicity) or Hawkes Broker Sweep Intensity lambda(t) >= 0.85,
            apply an instant 40-point health penalty and degrade gauge state.
        """
        var_max_safe = max(1e-6, float(var_max))
        var_ratio = max(0.0, float(var_99) / var_max_safe)
        vpin_clamped = max(0.0, min(1.0, float(vpin)))
        c_ratio = max(0.0, min(1.0, float(c_locked_ratio)))
        s_ratio = max(0.0, min(1.0, float(s_locked_ratio)))

        weighted_penalty = (
            0.35 * var_ratio
            + 0.30 * vpin_clamped
            + 0.20 * c_ratio
            + 0.15 * s_ratio
        )
        base_score = 100.0 * (1.0 - weighted_penalty)

        microstructure_triggered = (vpin_clamped >= 0.70) or (float(hawkes_intensity) >= 0.85)
        penalty_points = 40 if microstructure_triggered else 0
        final_float = max(0.0, min(100.0, base_score - float(penalty_points)))
        final_int = int(round(final_float))

        if final_int >= 80 and not microstructure_triggered:
            status = "Optimal"
            color = "#10B981"
        elif final_int >= 55:
            status = "Attention"
            color = "#F59E0B"
        else:
            status = "Critical"
            color = "#EF4444"

        cvar_val = float(cvar_1d) if cvar_1d is not None else float(var_99) * 1.18

        return HealthGaugeTelemetry(
            score=final_int,
            raw_score=round(final_float, 2),
            status=status,
            status_color=color,
            var_99_pct=round(float(var_99) * 100.0, 2),
            var_max_pct=round(var_max_safe * 100.0, 2),
            cvar_1d_pct=round(cvar_val * 100.0, 2),
            vpin=round(vpin_clamped, 4),
            hawkes_intensity=round(float(hawkes_intensity), 4),
            c_locked_ratio=round(c_ratio, 4),
            s_locked_ratio=round(s_ratio, 4),
            cdsc_t2_lockup_pct=round(c_ratio * 100.0, 2),
            microstructure_penalty_applied=microstructure_triggered,
            penalty_points=penalty_points,
            slicing_engine_paused=(vpin_clamped > 0.50 or microstructure_triggered),
        )

    # -------------------------------------------------------------------------
    # 1. Past Horizon Evaluators
    # -------------------------------------------------------------------------
    def evaluate_past_horizon(
        self,
        committed_unsettled_cash: float = 0.0,
        stcgt_liquidated_with_ltcgt_available: bool = False,
        merkle_verification_passed: bool = True,
        symbol: Optional[str] = None,
        reference_time: Optional[datetime] = None,
    ) -> List[TriHorizonAlert]:
        ts = (reference_time or datetime.now(timezone.utc)).isoformat()
        alerts: List[TriHorizonAlert] = []

        if committed_unsettled_cash > 0.0:
            alerts.append(
                TriHorizonAlert(
                    alert_id=f"ALT-PAST-SETTLE-{int(datetime.now(timezone.utc).timestamp())}",
                    code="WARN_PAST_SETTLE_VIOLATION",
                    horizon=HorizonType.PAST.value,
                    severity=AlertSeverity.CRITICAL.value,
                    symbol=symbol,
                    title="T+2 Unsettled Cash Commitment Violation",
                    message=(
                        f"Executed order committed NPR {committed_unsettled_cash:,.2f} bound by "
                        f"active CDSC T+2 settlement locks."
                    ),
                    metric_value=round(committed_unsettled_cash, 2),
                    threshold_value=0.0,
                    remediation_action="Halt secondary buy allocation and isolate unsettled BOID proceeds.",
                    timestamp=ts,
                )
            )

        if stcgt_liquidated_with_ltcgt_available:
            alerts.append(
                TriHorizonAlert(
                    alert_id=f"ALT-PAST-TAX-{int(datetime.now(timezone.utc).timestamp())}",
                    code="WARN_PAST_TAX_MISMATCH",
                    horizon=HorizonType.PAST.value,
                    severity=AlertSeverity.WARNING.value,
                    symbol=symbol,
                    title="Sub-Optimal CGT Lot Selection Detected",
                    message=(
                        f"Short-Term CGT lot (7.5% tax bracket) was liquidated for {symbol or 'asset'} "
                        f"while an eligible Long-Term CGT lot (5.0% bracket, >365d) was available."
                    ),
                    metric_value=0.075,
                    threshold_value=0.050,
                    remediation_action="Re-bind CDSC EDIS settlement instruction to long-term BOID lot.",
                    timestamp=ts,
                )
            )

        if not merkle_verification_passed:
            alerts.append(
                TriHorizonAlert(
                    alert_id=f"ALT-PAST-MERKLE-{int(datetime.now(timezone.utc).timestamp())}",
                    code="WARN_PAST_MERKLE_MISMATCH",
                    horizon=HorizonType.PAST.value,
                    severity=AlertSeverity.CRITICAL.value,
                    symbol=symbol,
                    title="Cryptographic Merkle Audit Root Mismatch",
                    message=(
                        "Local child-order HMAC-SHA256 execution leaf failed verification against "
                        "anchored Merkle Root R_Merkle."
                    ),
                    metric_value=0.0,
                    threshold_value=1.0,
                    remediation_action="Quarantine execution ledger and trigger full forensic audit replay.",
                    timestamp=ts,
                )
            )

        return alerts

    # -------------------------------------------------------------------------
    # 2. Present Horizon Evaluators
    # -------------------------------------------------------------------------
    def evaluate_present_horizon(
        self,
        vpin: float,
        vpin_mu: float = 0.22,
        vpin_sigma: float = 0.14,
        child_slice_qty: int = 0,
        top3_lob_depth: int = 1000,
        hawkes_intensity: float = 0.04,
        decision_price: float = 1000.0,
        fill_price: float = 1000.0,
        symbol: Optional[str] = None,
        reference_time: Optional[datetime] = None,
    ) -> List[TriHorizonAlert]:
        ts = (reference_time or datetime.now(timezone.utc)).isoformat()
        alerts: List[TriHorizonAlert] = []

        vpin_threshold = max(0.50, float(vpin_mu) + 2.0 * float(vpin_sigma))
        if float(vpin) > vpin_threshold or float(vpin) > 0.50:
            alerts.append(
                TriHorizonAlert(
                    alert_id=f"ALT-PRES-VPIN-{symbol or 'PORT'}",
                    code="WARN_PRES_VPIN_TOXICITY",
                    horizon=HorizonType.PRESENT.value,
                    severity=(
                        AlertSeverity.CRITICAL.value
                        if float(vpin) >= 0.70
                        else AlertSeverity.WARNING.value
                    ),
                    symbol=symbol,
                    title="Order Flow Toxicity Shield Triggered (VPIN)",
                    message=(
                        f"VPIN={vpin:.2f} exceeds 2-sigma toxicity boundary ({vpin_threshold:.2f}). "
                        f"Passive slicing engine paused and Health Gauge penalized."
                    ),
                    metric_value=round(float(vpin), 4),
                    threshold_value=round(vpin_threshold, 4),
                    remediation_action="Pause TWAP/VWAP child slicing until VPIN normalizes below 0.50.",
                    timestamp=ts,
                )
            )

        lob_cap = 0.15 * float(max(1, top3_lob_depth))
        if float(child_slice_qty) > lob_cap:
            alerts.append(
                TriHorizonAlert(
                    alert_id=f"ALT-PRES-LOB-{symbol or 'PORT'}",
                    code="WARN_PRES_LOB_DEPLETION",
                    horizon=HorizonType.PRESENT.value,
                    severity=AlertSeverity.WARNING.value,
                    symbol=symbol,
                    title="15% Level-2 LOB Depth Ceiling Breached",
                    message=(
                        f"Child slice ({child_slice_qty:,} sh) exceeds 15% of active top-3 LOB depth "
                        f"({lob_cap:,.0f} sh out of {top3_lob_depth:,} sh)."
                    ),
                    metric_value=float(child_slice_qty),
                    threshold_value=round(lob_cap, 2),
                    remediation_action="Throttle child order cadence and partition into smaller TWAP clips.",
                    timestamp=ts,
                )
            )

        if float(hawkes_intensity) >= 0.85:
            alerts.append(
                TriHorizonAlert(
                    alert_id=f"ALT-PRES-HAWKES-{symbol or 'PORT'}",
                    code="WARN_PRES_HAWKES_SWEEP",
                    horizon=HorizonType.PRESENT.value,
                    severity=AlertSeverity.CRITICAL.value,
                    symbol=symbol,
                    title="Predatory Hawkes Broker Syndicate Sweep",
                    message=(
                        f"Self-exciting Hawkes intensity lambda(t)={hawkes_intensity:.2f} >= 0.85 "
                        f"indicates coordinated broker accumulation/sweep loop."
                    ),
                    metric_value=round(float(hawkes_intensity), 4),
                    threshold_value=0.85,
                    remediation_action="Switch execution router to dark iceberg clips and apply 40-pt health penalty.",
                    timestamp=ts,
                )
            )

        if decision_price > 0:
            slippage_bps = abs(float(fill_price) - float(decision_price)) / float(decision_price) * 10_000.0
            if slippage_bps > 25.0:
                alerts.append(
                    TriHorizonAlert(
                        alert_id=f"ALT-PRES-SLIP-{symbol or 'PORT'}",
                        code="WARN_PRES_SLIPPAGE_EXCEEDED",
                        horizon=HorizonType.PRESENT.value,
                        severity=AlertSeverity.WARNING.value,
                        symbol=symbol,
                        title="Execution Implementation Shortfall > 25 bps",
                        message=(
                            f"Filled price NPR {fill_price:,.2f} deviated {slippage_bps:.1f} bps "
                            f"from decision price NPR {decision_price:,.2f} (> 25.0 bps limit)."
                        ),
                        metric_value=round(slippage_bps, 2),
                        threshold_value=25.0,
                        remediation_action="Recalibrate limit order offset to passive mid-spread peg.",
                        timestamp=ts,
                    )
                )

        return alerts

    # -------------------------------------------------------------------------
    # 3. Future Horizon Evaluators
    # -------------------------------------------------------------------------
    def evaluate_future_horizon(
        self,
        projected_var_99: float,
        held_asset_ranks: Optional[Dict[str, int]] = None,
        promoter_cliff_days: Optional[Dict[str, float]] = None,
        raw_condition_number: float = 1.8,
        reference_time: Optional[datetime] = None,
    ) -> List[TriHorizonAlert]:
        ts = (reference_time or datetime.now(timezone.utc)).isoformat()
        alerts: List[TriHorizonAlert] = []

        if float(projected_var_99) > 0.035:
            alerts.append(
                TriHorizonAlert(
                    alert_id="ALT-FUT-VAR-99",
                    code="WARN_FUT_VAR_EXPANSION",
                    horizon=HorizonType.FUTURE.value,
                    severity=AlertSeverity.CRITICAL.value,
                    symbol=None,
                    title="Projected 1-Day VaR_99 Expansion Breach",
                    message=(
                        f"Projected 1-day VaR_99 ({projected_var_99*100:.2f}% of NAV) exceeds "
                        f"3.50% institutional risk ceiling."
                    ),
                    metric_value=round(float(projected_var_99) * 100.0, 2),
                    threshold_value=3.50,
                    remediation_action="Execute Schur-RA-HRP defensive de-risking rebalance immediately.",
                    timestamp=ts,
                )
            )

        if held_asset_ranks:
            for sym, rank_val in held_asset_ranks.items():
                if rank_val in (14, 15):
                    alerts.append(
                        TriHorizonAlert(
                            alert_id=f"ALT-FUT-RANK-{sym}",
                            code="WARN_FUT_RANK_DECAY",
                            horizon=HorizonType.FUTURE.value,
                            severity=AlertSeverity.WARNING.value,
                            symbol=sym,
                            title=f"Schur-RA-HRP Rank Decay Warning ({sym})",
                            message=(
                                f"Held position {sym} degraded to Schur rank #{rank_val} "
                                f"(approaching Rank-15 Dual-Band Hysteresis exit cliff)."
                            ),
                            metric_value=float(rank_val),
                            threshold_value=15.0,
                            remediation_action=f"Pre-stage LTCGT tax lots for {sym} in case rank degrades > 15.",
                            timestamp=ts,
                        )
                    )

        if promoter_cliff_days:
            for sym, days_rem in promoter_cliff_days.items():
                if 0.0 <= float(days_rem) <= 14.0:
                    alerts.append(
                        TriHorizonAlert(
                            alert_id=f"ALT-FUT-PROMOTER-{sym}",
                            code="WARN_FUT_PROMOTER_CLIFF",
                            horizon=HorizonType.FUTURE.value,
                            severity=AlertSeverity.WARNING.value,
                            symbol=sym,
                            title=f"3-Year Promoter Lock-In Expiry Cliff ({sym})",
                            message=(
                                f"Mandatory 3-year promoter share lock-in for {sym} expires in "
                                f"{days_rem:.1f} days (<= 14d threshold). Forced w_{sym}=0 active."
                            ),
                            metric_value=round(float(days_rem), 2),
                            threshold_value=14.0,
                            remediation_action=f"Maintain zero target weight w_{sym}=0 to shield against supply shock.",
                            timestamp=ts,
                        )
                    )

        if float(raw_condition_number) > 100.0:
            alerts.append(
                TriHorizonAlert(
                    alert_id="ALT-FUT-KAPPA",
                    code="WARN_FUT_COND_NUMBER",
                    horizon=HorizonType.FUTURE.value,
                    severity=AlertSeverity.INFO.value,
                    symbol=None,
                    title="Covariance Ill-Conditioning Detected (Ledoit-Wolf Active)",
                    message=(
                        f"Sample covariance condition number kappa={raw_condition_number:.1f} > 100.0. "
                        f"Ledoit-Wolf spectral shrinkage engaged to bound kappa <= 2.0."
                    ),
                    metric_value=round(float(raw_condition_number), 2),
                    threshold_value=100.0,
                    remediation_action="Ledoit-Wolf shrinkage automatically applied prior to Schur bisection.",
                    timestamp=ts,
                )
            )

        return alerts
