"""
Universal Local Device File Importer (`engine/local_file_importer.py`).

Parses portfolio holdings from files uploaded/selected from the user's local device:
- `.csv`, `.tsv`, `.txt` (MeroShare "My Shares", MeroShare "My Portfolio", TMS Exports, Custom CSVs)
- `.xlsx` (Native Excel OpenXML workbooks via standard-library `zipfile` + `xml.etree.ElementTree`)
- `.xls` (MeroShare / TMS HTML-table `.xls` exports or tab-delimited `.xls` files)
- `.json` (Array of holdings, object with `items`/`tax_lots`/`data`, or NEPSE floorsheet JSON)

Strictly enforces `APEX_STRICT_PRICE_AND_PREDICTION_PROTOCOL_V1`:
- Never synthesizes or invents prices.
- Resolves missing LTPs strictly from `StrictPriceIntegrityEngine.verified_nepse_closes`
  (`REAL_NEPSE_HISTORICAL_CLOSE`) or explicit user-provided values (`USER_ENTERED_PRICE`).
"""

