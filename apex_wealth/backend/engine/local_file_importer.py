def _norm_header(h: str) -> str:
    return re.sub(r"[^a-z0-9]", "", str(h or "").strip().lower())


def _clean_number(val: Any) -> Optional[float]:
    if val is None:
        return None
    s = str(val).strip()
    if not s or s in ("-", "--", "N/A", "null", "None"):
        return None
    # Strip currency prefixes like NPR, Rs., commas, spaces, parentheses
    s = re.sub(r"(?i)^(npr|rs\.?|\$)\s*", "", s)
    s = s.replace(",", "").strip()
    try:
        return float(s)
    except ValueError:
        return None


class _SimpleHTMLTableParser(HTMLParser):
    """Extracts 2D rows from HTML-based `.xls` exports generated by MeroShare / TMS."""

    def __init__(self) -> None:
        super().__init__()
        self.rows: List[List[str]] = []
        self._in_tr = False
        self._in_cell = False
        self._current_row: List[str] = []
        self._current_cell: List[str] = []

    def handle_starttag(self, tag: str, attrs: list) -> None:
        t = tag.lower()
        if t == "tr":
            self._in_tr = True
            self._current_row = []
        elif t in ("td", "th") and self._in_tr:
            self._in_cell = True
            self._current_cell = []

    def handle_data(self, data: str) -> None:
        if self._in_cell:
            self._current_cell.append(data)

    def handle_endtag(self, tag: str) -> None:
        t = tag.lower()
        if t in ("td", "th") and self._in_cell:
            self._in_cell = False
            self._current_row.append("".join(self._current_cell).strip())
        elif t == "tr" and self._in_tr:
            self._in_tr = False
            if any(c.strip() for c in self._current_row):
                self.rows.append(self._current_row)


def _extract_xlsx_rows(raw_bytes: bytes) -> List[List[str]]:
    """
    Zero-dependency native `.xlsx` reader using Python's built-in `zipfile` and `xml.etree.ElementTree`.
    Reads `xl/sharedStrings.xml` and `xl/worksheets/sheet1.xml`.
    """
    rows_out: List[List[str]] = []
    with zipfile.ZipFile(io.BytesIO(raw_bytes)) as zf:
        shared_strings: List[str] = []
        if "xl/sharedStrings.xml" in zf.namelist():
            ss_xml = zf.read("xl/sharedStrings.xml")
            ss_root = ET.fromstring(ss_xml)
            for si in ss_root.iter():
                if si.tag.endswith("}si") or si.tag == "si":
                    texts = [
                        t.text or ""
                        for t in si.iter()
                        if t.tag.endswith("}t") or t.tag == "t"
                    ]
                    shared_strings.append("".join(texts))

        sheet_names = [
            name
            for name in sorted(zf.namelist())
            if name.startswith("xl/worksheets/sheet") and name.endswith(".xml")
        ]
        if not sheet_names:
            return []

        sheet_xml = zf.read(sheet_names[0])
        sheet_root = ET.fromstring(sheet_xml)

        def _col_letters_to_index(cell_ref: str) -> int:
            letters = "".join(ch for ch in cell_ref if ch.isalpha()).upper()
            idx = 0
            for ch in letters:
                idx = idx * 26 + (ord(ch) - ord("A") + 1)
            return max(0, idx - 1)

        for row_el in sheet_root.iter():
            if not (row_el.tag.endswith("}row") or row_el.tag == "row"):
                continue
            row_cells: Dict[int, str] = {}
            max_col = -1
            for c_el in row_el:
                if not (c_el.tag.endswith("}c") or c_el.tag == "c"):
                    continue
                ref = c_el.attrib.get("r", "")
                c_type = c_el.attrib.get("t", "")
                col_idx = _col_letters_to_index(ref) if ref else (max_col + 1)
                max_col = max(max_col, col_idx)
                val_text = ""
                for child in c_el:
                    if child.tag.endswith("}v") or child.tag == "v":
                        val_text = child.text or ""
                    elif child.tag.endswith("}is") or child.tag == "is":
                        texts = [
                            t.text or ""
                            for t in child.iter()
                            if t.tag.endswith("}t") or t.tag == "t"
                        ]
                        val_text = "".join(texts)
                if c_type == "s" and val_text.isdigit():
                    s_idx = int(val_text)
                    if 0 <= s_idx < len(shared_strings):
                        val_text = shared_strings[s_idx]
                row_cells[col_idx] = val_text.strip()
            if max_col >= 0:
                row_list = [row_cells.get(i, "") for i in range(max_col + 1)]
                if any(cell for cell in row_list):
                    rows_out.append(row_list)
    return rows_out


def _rows_to_normalized_holdings(
    rows: List[List[str]],
    integrity_engine: StrictPriceIntegrityEngine,
    default_sub_account: str = "Personal",
) -> List[Dict[str, Any]]:
    """
    Convert a 2D table of strings (either with a header row or headerless) into validated holding dicts.
    """
    if not rows:
        return []

    # Find the header row (sometimes MeroShare exports have 1-3 title rows before the table header)
    header_row_idx: Optional[int] = None
    col_map: Dict[str, int] = {}

    for r_idx, row in enumerate(rows[:10]):
        norm_cells = [_norm_header(c) for c in row]
        sym_col = next((i for i, h in enumerate(norm_cells) if h in SYMBOL_HEADERS), None)
        qty_col = next((i for i, h in enumerate(norm_cells) if h in QUANTITY_HEADERS), None)
        if sym_col is not None and qty_col is not None:
            header_row_idx = r_idx
            col_map["symbol"] = sym_col
            col_map["quantity"] = qty_col
            price_col = next(
                (i for i, h in enumerate(norm_cells) if h in PURCHASE_PRICE_HEADERS and i != sym_col and i != qty_col),
                None,
            )
            ltp_col = next(
                (i for i, h in enumerate(norm_cells) if h in LTP_HEADERS and i not in (sym_col, qty_col, price_col)),
                None,
            )
            days_col = next(
                (i for i, h in enumerate(norm_cells) if h in HOLDING_DAYS_HEADERS),
                None,
            )
            acc_col = next(
                (i for i, h in enumerate(norm_cells) if h in ACCOUNT_HEADERS),
                None,
            )
            prom_col = next(
                (i for i, h in enumerate(norm_cells) if h in PROMOTER_HEADERS),
                None,
            )
            if price_col is not None:
                col_map["purchase_price"] = price_col
            if ltp_col is not None:
                col_map["ltp"] = ltp_col
            if days_col is not None:
                col_map["holding_days"] = days_col
            if acc_col is not None:
                col_map["sub_account_id"] = acc_col
            if prom_col is not None:
                col_map["promoter"] = prom_col
            break

    parsed_items: List[Dict[str, Any]] = []

    if header_row_idx is not None:
        data_rows = rows[header_row_idx + 1 :]
        for row in data_rows:
            if not row or len(row) <= max(col_map["symbol"], col_map["quantity"]):
                continue
            raw_sym = str(row[col_map["symbol"]]).strip().upper()
            # Clean MeroShare script format if it has spaces or suffixes
            sym = re.sub(r"[^A-Z0-9]", "", raw_sym.split()[0]) if raw_sym else ""
            if not sym or sym in ("TOTAL", "GRANDTOTAL", "SN", "SRNO"):
                continue

            qty_val = _clean_number(row[col_map["quantity"]])
            if qty_val is None or qty_val <= 0:
                continue
            quantity = int(round(qty_val))

            raw_buy = (
                _clean_number(row[col_map["purchase_price"]])
                if "purchase_price" in col_map and col_map["purchase_price"] < len(row)
                else None
            )
            raw_ltp = (
                _clean_number(row[col_map["ltp"]])
                if "ltp" in col_map and col_map["ltp"] < len(row)
                else None
            )

            # Check verified NEPSE close for this symbol
            verified_close_info = integrity_engine.verified_nepse_closes.get(sym)
            verified_close_price = float(verified_close_info[0]) if verified_close_info else None
            verified_close_date = verified_close_info[1] if verified_close_info else None

            # Determine purchase_price (WACC / Buy Price)
            if raw_buy is not None and raw_buy > 0:
                purchase_price = round(float(raw_buy), 2)
                buy_price_note = "From File (Buy Price / WACC)"
            elif raw_ltp is not None and raw_ltp > 0:
                purchase_price = round(float(raw_ltp), 2)
                buy_price_note = "From File LTP (No WACC column in file)"
            elif verified_close_price is not None and verified_close_price > 0:
                purchase_price = round(verified_close_price, 2)
                buy_price_note = f"Verified NEPSE Close ({verified_close_date}) — Edit WACC if needed"
            else:
                continue

            # Determine LTP & Provenance strictly per protocol
            prov = integrity_engine.resolve_verified_price(
                symbol=sym,
                user_supplied_ltp=raw_ltp if (raw_ltp is not None and raw_ltp > 0) else None,
                user_purchase_price=purchase_price,
            )

            days_val = (
                _clean_number(row[col_map["holding_days"]])
                if "holding_days" in col_map and col_map["holding_days"] < len(row)
                else None
            )
            holding_days = int(days_val) if (days_val is not None and days_val >= 0) else 400

            sub_acc = (
                str(row[col_map["sub_account_id"]]).strip()
                if "sub_account_id" in col_map and col_map["sub_account_id"] < len(row) and str(row[col_map["sub_account_id"]]).strip()
                else default_sub_account
            )

            is_promoter = False
            if "promoter" in col_map and col_map["promoter"] < len(row):
                p_str = str(row[col_map["promoter"]]).strip().lower()
                is_promoter = p_str in ("true", "1", "yes", "y", "promoter", "locked")

            parsed_items.append({
                "sub_account_id": sub_acc,
                "symbol": sym,
                "quantity": quantity,
                "purchase_price": purchase_price,
                "buy_price_note": buy_price_note,
                "ltp": raw_ltp if (raw_ltp is not None and raw_ltp > 0) else None,
                "resolved_ltp": prov.price,
                "ltp_source_type": prov.source_type,
                "ltp_source_detail": prov.source_detail,
                "ltp_as_of_date": prov.as_of_date,
                "holding_days": holding_days,
                "is_promoter_locked": is_promoter,
            })
        return parsed_items

    # Fallback: Headerless rows (`SYMBOL, QUANTITY, BUY_PRICE [, LTP, HOLDING_DAYS, SUB_ACCOUNT]`)
    for row in rows:
        tokens = [str(c).strip() for c in row if str(c).strip()]
        if len(tokens) < 2:
            continue
        # Handle Case where S.N. is column 0 (e.g. `1, NABIL, 500, 485`)
        start_idx = 1 if (tokens[0].isdigit() and len(tokens) >= 3 and re.match(r"^[A-Za-z]", tokens[1])) else 0
        if len(tokens) - start_idx < 2:
            continue
        raw_sym = tokens[start_idx].upper()
        sym = re.sub(r"[^A-Z0-9]", "", raw_sym)
        if not sym or sym.isdigit() or sym in ("SYMBOL", "SCRIP", "SCRIPT", "TOTAL"):
            continue
        qty_val = _clean_number(tokens[start_idx + 1])
        if qty_val is None or qty_val <= 0:
            continue
        quantity = int(round(qty_val))

        raw_buy = _clean_number(tokens[start_idx + 2]) if len(tokens) > start_idx + 2 else None
        raw_ltp = _clean_number(tokens[start_idx + 3]) if len(tokens) > start_idx + 3 else None
        raw_days = _clean_number(tokens[start_idx + 4]) if len(tokens) > start_idx + 4 else None
        sub_acc = (
            tokens[start_idx + 5]
            if len(tokens) > start_idx + 5
            else default_sub_account
        )

        verified_close_info = integrity_engine.verified_nepse_closes.get(sym)
        verified_close_price = float(verified_close_info[0]) if verified_close_info else None
        verified_close_date = verified_close_info[1] if verified_close_info else None

        if raw_buy is not None and raw_buy > 0:
            purchase_price = round(float(raw_buy), 2)
            buy_price_note = "From File Column 3"
        elif verified_close_price is not None and verified_close_price > 0:
            purchase_price = round(verified_close_price, 2)
            buy_price_note = f"Verified NEPSE Close ({verified_close_date})"
        else:
            continue

        prov = integrity_engine.resolve_verified_price(
            symbol=sym,
            user_supplied_ltp=raw_ltp if (raw_ltp is not None and raw_ltp > 0) else None,
            user_purchase_price=purchase_price,
        )

        parsed_items.append({
            "sub_account_id": sub_acc,
            "symbol": sym,
            "quantity": quantity,
            "purchase_price": purchase_price,
            "buy_price_note": buy_price_note,
            "ltp": raw_ltp if (raw_ltp is not None and raw_ltp > 0) else None,
            "resolved_ltp": prov.price,
            "ltp_source_type": prov.source_type,
            "ltp_source_detail": prov.source_detail,
            "ltp_as_of_date": prov.as_of_date,
            "holding_days": int(raw_days) if (raw_days is not None and raw_days >= 0) else 400,
            "is_promoter_locked": False,
        })

    return parsed_items


def parse_uploaded_portfolio_file(
    filename: str,
    raw_bytes: bytes,
    integrity_engine: StrictPriceIntegrityEngine,
    default_sub_account: str = "Personal",
) -> Tuple[List[Dict[str, Any]], str]:
    """
    Parse any local portfolio file (`.csv`, `.tsv`, `.txt`, `.json`, `.xlsx`, `.xls`)
    into a list of normalized holding records with verified price provenance.
    Returns `(items, detected_format_description)`.
    """
    fname_lower = (filename or "upload.csv").strip().lower()

    # 1. Native Excel `.xlsx` (ZIP container)
    if fname_lower.endswith(".xlsx") or raw_bytes[:4] == b"PK\x03\x04":
        rows = _extract_xlsx_rows(raw_bytes)
        items = _rows_to_normalized_holdings(rows, integrity_engine, default_sub_account)
        return items, "Excel Workbook (.xlsx)"

    text = raw_bytes.decode("utf-8-sig", errors="replace").strip()
    if not text:
        return [], "Empty File"

    # 2. JSON file (`.json` or starts with `[` / `{`)
    if fname_lower.endswith(".json") or text.startswith("[") or text.startswith("{"):
        try:
            data = json.loads(text)
            records = []
            if isinstance(data, list):
                records = data
            elif isinstance(data, dict):
                for key in ("items", "tax_lots", "holdings", "portfolio", "data", "rows"):
                    if isinstance(data.get(key), list):
                        records = data[key]
                        break
            rows_2d: List[List[str]] = [
                ["symbol", "quantity", "purchase_price", "ltp", "holding_days", "sub_account_id", "is_promoter_locked"]
            ]
            for rec in records:
                if not isinstance(rec, dict):
                    continue
                sym = (
                    rec.get("symbol")
                    or rec.get("scrip")
                    or rec.get("script")
                    or rec.get("stockSymbol")
                    or rec.get("ticker")
                    or ""
                )
                qty = (
                    rec.get("quantity")
                    or rec.get("qty")
                    or rec.get("shares")
                    or rec.get("kitta")
                    or rec.get("currentBalance")
                    or rec.get("contractQuantity")
                    or 0
                )
                buy = (
                    rec.get("purchase_price")
                    or rec.get("buy_price")
                    or rec.get("wacc")
                    or rec.get("price")
                    or rec.get("contractRate")
                    or ""
                )
                ltp = rec.get("ltp") or rec.get("closePrice") or rec.get("closing_price") or ""
                days = rec.get("holding_days") or rec.get("days") or 400
                acc = rec.get("sub_account_id") or rec.get("sub_account_label") or rec.get("account_label") or default_sub_account
                prom = rec.get("is_promoter_locked") or False
                rows_2d.append([str(sym), str(qty), str(buy), str(ltp), str(days), str(acc), str(prom)])
            items = _rows_to_normalized_holdings(rows_2d, integrity_engine, default_sub_account)
            return items, "JSON Portfolio File (.json)"
        except Exception:
            pass

    # 3. HTML Table inside `.xls` (MeroShare / TMS frequently export HTML tables with `.xls` extension)
    if "<table" in text.lower() or "<tr" in text.lower():
        parser = _SimpleHTMLTableParser()
        parser.feed(text)
        items = _rows_to_normalized_holdings(parser.rows, integrity_engine, default_sub_account)
        return items, "MeroShare / TMS HTML Spreadsheet (.xls)"

    # 4. Delimited Text (`.csv`, `.tsv`, `.txt`)
    lines = [ln for ln in text.splitlines() if ln.strip()]
    sample = "\n".join(lines[:10])
    rows_csv: List[List[str]] = []
    if "\t" in sample:
        reader = csv.reader(io.StringIO(text), delimiter="\t")
        rows_csv = [r for r in reader if any(c.strip() for c in r)]
        fmt_label = "Tab-Separated Values (.tsv / MeroShare Export)"
    elif ";" in sample and "," not in sample:
        reader = csv.reader(io.StringIO(text), delimiter=";")
        rows_csv = [r for r in reader if any(c.strip() for c in r)]
        fmt_label = "Semicolon-Delimited CSV (.csv)"
    else:
        reader = csv.reader(io.StringIO(text))
        rows_csv = [r for r in reader if any(c.strip() for c in r)]
        # If single-column whitespace-separated lines, split on whitespace
        if rows_csv and all(len(r) == 1 for r in rows_csv):
            rows_csv = [re.split(r"\s+", r[0].strip()) for r in rows_csv if r[0].strip()]
        fmt_label = "Comma-Separated Values (.csv)"

    items = _rows_to_normalized_holdings(rows_csv, integrity_engine, default_sub_account)
    return items, fmt_label
